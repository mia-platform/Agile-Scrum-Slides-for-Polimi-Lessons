-- Lesson sessions, players, question runs and answers. Idempotent: safe to re-run.
-- Applied by the preview on start and again by server.js. Change it with a new numbered file.

CREATE TABLE IF NOT EXISTS deck_sessions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  event_date date,
  place text,
  status text NOT NULL DEFAULT 'draft',          -- draft | active | archived
  config jsonb NOT NULL DEFAULT '{}'::jsonb,     -- title, subtitle, speaker, hiddenSlides, questions
  created_at timestamptz NOT NULL DEFAULT now(),
  activated_at timestamptz,
  archived_at timestamptz
);
CREATE INDEX IF NOT EXISTS deck_sessions_status_idx ON deck_sessions (status);

CREATE TABLE IF NOT EXISTS deck_players (
  id text PRIMARY KEY,
  session_id bigint NOT NULL REFERENCES deck_sessions(id) ON DELETE CASCADE,
  name text NOT NULL,
  joined_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS deck_players_session_idx ON deck_players (session_id);

CREATE TABLE IF NOT EXISTS deck_runs (
  session_id bigint NOT NULL REFERENCES deck_sessions(id) ON DELETE CASCADE,
  question_id text NOT NULL,
  status text NOT NULL DEFAULT 'idle',
  started_at timestamptz,
  ends_at timestamptz,
  revealed boolean NOT NULL DEFAULT false,
  hidden jsonb NOT NULL DEFAULT '[]'::jsonb,
  PRIMARY KEY (session_id, question_id)
);

CREATE TABLE IF NOT EXISTS deck_answers (
  session_id bigint NOT NULL REFERENCES deck_sessions(id) ON DELETE CASCADE,
  question_id text NOT NULL,
  player_id text NOT NULL REFERENCES deck_players(id) ON DELETE CASCADE,
  value jsonb NOT NULL,
  points int NOT NULL DEFAULT 0,
  answered_at timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (session_id, question_id, player_id)
);

CREATE TABLE IF NOT EXISTS deck_settings (
  key text PRIMARY KEY,
  value jsonb NOT NULL
);
